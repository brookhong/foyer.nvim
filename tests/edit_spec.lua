local H = dofile('tests/helpers.lua')
local foyer = H.foyer({})

H.test('edit_selection() edits the selection in a float and writes it back', function()
    vim.cmd('enew')
    local buf = vim.api.nvim_get_current_buf()
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'keep', 'one', 'two', 'keep' })
    H.press(function() foyer.edit_selection() end, '2GVj')
    local s = H.state()
    H.ok(s.float, 'a float')
    H.eq({ 'one', 'two' }, vim.api.nvim_buf_get_lines(0, 0, -1, false), 'the selection, without a trailing blank')
    -- Sized from the selection: its rows, or its wrapped length plus two.
    H.eq(3, vim.api.nvim_win_get_height(s.win), 'sized from the selection, not the default 10')
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'ONE', 'TWO', 'THREE' })
    vim.cmd('stopinsert')
    H.feed('<CR>')
    H.eq(buf, H.state().buf, 'back in the buffer')
    H.eq({ 'keep', 'ONE', 'TWO', 'THREE', 'keep' }, vim.api.nvim_buf_get_lines(buf, 0, -1, false), 'written back')
end)

H.test('<C-o> in edit_selection()\'s float leads nowhere', function()
    vim.cmd('edit README.md')
    vim.cmd('enew')
    local buf = vim.api.nvim_get_current_buf()
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { 'one' })
    H.press(function() foyer.edit_selection() end, 'V')
    local s = H.state()
    vim.cmd('stopinsert')
    H.feed('<C-o>')
    H.eq(s.buf, H.state().buf, 'still the selection, not a file from the jump list')
    H.feed('<C-c>')
end)

-- Select with {keys} in a buffer of {lines}, replace the float's text with
-- {edited}, send, and return the buffer's lines.
local function round_trip(lines, keys, edited)
    vim.cmd('enew')
    local buf = vim.api.nvim_get_current_buf()
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines)
    vim.api.nvim_win_set_cursor(0, { 1, 0 })
    H.press(function() foyer.edit_selection() end, keys)
    local float = H.state().buf
    local shown = vim.api.nvim_buf_get_lines(float, 0, -1, false)
    vim.api.nvim_buf_set_lines(float, 0, -1, false, edited)
    vim.cmd('stopinsert')
    H.feed('<CR>')
    H.eq(buf, H.state().buf, 'back in the buffer')
    return vim.api.nvim_buf_get_lines(buf, 0, -1, false), shown
end

H.test('registers are left as they were, a and the unnamed one among them', function()
    vim.fn.setreg('a', 'my macro')
    vim.fn.setreg('1', 'a delete')
    vim.fn.setreg('-', 'a small one')
    vim.fn.setreg('0', 'my yank')
    vim.fn.setreg('"', 'my yank')
    local before = vim.fn.getreginfo('"').points_to
    round_trip({ 'one', 'two' }, 'V', { 'ONE' })
    H.eq('my macro', vim.fn.getreg('a'), 'register a')
    H.eq('my yank', vim.fn.getreg('"'), 'the unnamed register')
    H.eq(before, vim.fn.getreginfo('"').points_to, 'pointing where it did')
    H.eq('my yank', vim.fn.getreg('0'), 'register 0')
    H.eq('a delete', vim.fn.getreg('1'), 'register 1, not given the replaced text')
    H.eq('a small one', vim.fn.getreg('-'), 'the small delete register')
end)

H.test('closed without sending, registers are still as they were', function()
    vim.fn.setreg('a', 'my macro')
    vim.cmd('enew')
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'one' })
    H.press(function() foyer.edit_selection() end, 'V')
    vim.cmd('stopinsert')
    H.feed('<C-c>')
    H.eq('my macro', vim.fn.getreg('a'), 'register a')
end)

H.test('characterwise: only the selected text, multibyte at its end', function()
    local got, shown = round_trip({ 'héllo wörld', 'sécond line' }, '0lvj3l', { 'X', 'Y' })
    H.eq({ 'éllo wörld', 'sécon' }, shown, 'what the float shows')
    H.eq({ 'hX', 'Yd line' }, got, 'written back')
    got = round_trip({ 'a wörd here' }, '02lvl', { 'W' })
    H.eq({ 'a Wrd here' }, got, 'ending on a multibyte character')
end)

H.test('blockwise: each line\'s part replaced, fewer or more lines alike', function()
    local got, shown = round_trip({ 'abcdef', 'ghijkl', 'mnopqr' }, '0l<C-v>jjl', { '12', '34', '56' })
    H.eq({ 'bc', 'hi', 'no' }, shown, 'the block')
    H.eq({ 'a12def', 'g34jkl', 'm56pqr' }, got, 'one line each')
    got = round_trip({ 'abcdef', 'ghijkl', 'mnopqr' }, '0l<C-v>jl', { 'X' })
    H.eq({ 'aXdef', 'gjkl', 'mnopqr' }, got, 'fewer: the rest of the block emptied')
    got = round_trip({ 'abcdef', 'gh' }, '02l<C-v>l', { '1', '2', '3' })
    H.eq({ 'ab1ef', 'gh2', '  3' }, got, 'more: below, at the block\'s column, padded')
end)

H.finish()
